function videoWork(
  slug: string,
  alt: string,
  width: number,
  height: number,
): { cover: ProjectImage; gallery: ProjectVideo[] } {
  return {
    cover: {
      src: `/images/projects/${slug}/cover.webp`,
      thumb: `/images/projects/${slug}/cover-thumb.webp`,
      alt,
      width,
      height,
    },
    gallery: [
      {
        kind: "video",
        src: `/videos/projects/${slug}/tour.mp4`,
        poster: `/videos/projects/${slug}/poster.webp`,
        thumb: `/videos/projects/${slug}/poster-thumb.webp`,
        alt,
        width,
        height,
      },
    ],
  };
}

